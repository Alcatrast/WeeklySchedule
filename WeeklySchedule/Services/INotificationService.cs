namespace WeeklySchedule.Services;

public interface INotificationService
{
    /// <summary>
    /// Единственное разрешение, без которого уведомлений не будет вовсе.
    /// </summary>
    Task<bool> CheckPermissionAsync();

    /// <summary>
    /// Спрашивает разрешение и возвращает фактический итог диалога. Именно итог, а
    /// не void: раньше вызывающий ждал фиксированную паузу и перечитывал состояние
    /// наугад, и медленный ответ пользователя оставлял настройки закрытыми.
    /// </summary>
    Task<bool> RequestPermissionAsync();

    /// <summary>
    /// Системный экран уведомлений приложения. Нужен, когда разрешение отклонено
    /// окончательно: диалога больше не будет, и без этого обхода кнопка запроса
    /// осталась бы мертвой. Возвращает, удалось ли открыть экран.
    /// </summary>
    Task<bool> OpenNotificationSettingsAsync();

    /// <summary>
    /// Может ли система будить приложение точно в срок. Это не право на доставку,
    /// а только ее точность: будильники ставятся флагом «разрешено в простое», и
    /// без точности они все равно срабатывают, но с задержкой до десяти минут —
    /// Doze пропускает такой будильник примерно раз в девять минут на приложение.
    /// Отдельно от <see cref="CheckPermissionAsync"/> именно поэтому — отказ здесь
    /// не должен закрывать пользователю настройки уведомлений.
    /// </summary>
    Task<bool> CanScheduleExactAlarmsAsync();

    /// <summary>
    /// Открывает системный экран выдачи точности. Возвращает, удалось ли его
    /// показать: на части прошивок такого экрана нет, и молчаливое нажатие в никуда
    /// пользователю не объяснить.
    /// </summary>
    Task<bool> RequestExactAlarmsAsync();

    /// <summary>
    /// Ставит еженедельное напоминание за <paramref name="minutesBefore"/> минут до
    /// начала пары. Реализация сама находит ближайшее будущее вхождение: расписание
    /// недельное, поэтому дня недели и времени начала достаточно, а конкретная дата
    /// зависит от часового пояса и перевода часов и считается на стороне платформы.
    /// </summary>
    void ScheduleNotification(Guid timelineId, Guid lessonId, string title, string body,
        DayOfWeek day, TimeSpan startTime, int minutesBefore);

    void CancelAllNotifications();
}
